def enrich_math(text, actions, linear_mode=False):
    blocks=re.split(r'(?=^### 第)',text,flags=re.M)
    result=[blocks[0]]
    for block in blocks[1:]:
        title=block.splitlines()[0][4:]
        source,tests=(actions[title] if linear_mode else (None,actions[title]))
        lines=block.rstrip().splitlines()
        lines=[('- [ ] '+line[2:] if line.startswith('- ') else line) for line in lines]
        head=lines[0]+'\n\n'
        if source:
            head+=f'笔记：[[{source}|本讲完整笔记]]。\n\n'
        else:
            head+='教材：[[数学一/01-基础讲义/27张宇基础30讲概率.pdf|概率教材]]，页码见本节目录表。\n\n'
        head+='#### 完整知识点\n\n'
        content='\n'.join(lines[2:])
        head+=content+'\n\n#### 代表验收动作\n\n'
        head+='\n'.join('- [ ] '+x for x in tests)+'\n\n'
        result.append(head)
    return ''.join(result)

